/**
 * M209 — what actually ships, taken from the bundler rather than inferred.
 *
 * Two backstops walk `src/` and key every file they find:
 * `absenceClaims.test.ts` and `fabricatedFigures.test.ts`. Neither has a
 * single line of reachability logic, so both walk **dead code** — and a
 * finding in a file nothing imports costs real attention, changes nothing,
 * and inflates the report while doing it. `Sidebar.tsx` took three fixes in
 * thirteen days, mine included, before a hand-grep noticed it renders to
 * nobody.
 *
 * ── Why a build and not an import graph ──────────────────────────────────
 *
 * The tempting version walks imports from `main.tsx` and calls anything it
 * cannot reach an orphan. That is *"I found no importer"* — the fail-open
 * shape M191 already named, and the shape every blind instrument returns.
 * A resolver that quietly fails on an alias, a dynamic import or a barrel
 * file reports the same "no importer" as a genuinely dead file, and the
 * consequence lands in the dangerous direction: a **live** file excluded
 * from a backstop's population leaves silently, and the suite goes green.
 *
 * Rollup already answers the question exactly, because it had to in order to
 * emit the bundle. Every `.js.map` carries the `sources` of the modules that
 * went into that chunk, so the union across chunks is the set of files that
 * genuinely ship. That is evidence of *shipping*, not absence of importers.
 *
 * ── How to run it ────────────────────────────────────────────────────────
 *
 *   VITE_BACKEND_URL=https://REPLACE_ME_API_ORIGIN npm run census
 *
 * Writes `src/lib/__tests__/shipped-modules.json`, which is committed. The
 * tests treat a missing or unreadable file as "we do not know what ships"
 * and exclude nothing — unknown means reachable means still keyed.
 *
 * The build goes to a scratch directory and its sourcemaps never leave it:
 * `dist/` is untouched and no `.map` is ever deployed.
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";

const OUT = "src/lib/__tests__/shipped-modules.json";
const scratch = mkdtempSync(join(tmpdir(), "recall-census-"));

try {
  execFileSync(
    "npx",
    ["vite", "build", "--sourcemap", "--outDir", scratch, "--emptyOutDir"],
    {
      stdio: "inherit",
      env: {
        ...process.env,
        // The census only needs the module graph, and the production build
        // refuses a localhost API on purpose (its own guard). Any non-local
        // value produces the same graph.
        VITE_BACKEND_URL: process.env.VITE_BACKEND_URL || "https://REPLACE_ME_API_ORIGIN",
      },
    }
  );

  const assets = join(scratch, "assets");
  const modules = new Set();

  for (const file of readdirSync(assets)) {
    if (!file.endsWith(".map")) continue;
    const map = JSON.parse(readFileSync(join(assets, file), "utf8"));
    for (const source of map.sources ?? []) {
      if (source.includes("node_modules")) continue;
      const marker = source.lastIndexOf("/src/");
      if (marker === -1) continue;
      modules.add(source.slice(marker + "/src/".length));
    }
  }

  if (modules.size === 0) {
    throw new Error(
      "The census found no source modules. Refusing to write a file that " +
        "would mark the entire codebase dead."
    );
  }

  writeFileSync(
    OUT,
    JSON.stringify(
      {
        note:
          "Generated by scripts/module-census.mjs from the bundler's own " +
          "sourcemaps — the modules that actually ship. Regenerate with " +
          "`npm run census`. Never edit by hand.",
        modules: [...modules].sort(),
      },
      null,
      2
    ) + "\n"
  );

  console.log(`\n${modules.size} source modules ship. Written to ${OUT}`);
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
